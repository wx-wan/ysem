// 通过中文名或代码查找国家
export function findCountry(name?: string): CountryData | undefined {
  if (!name) return undefined;
  const trimmed = name.trim();
  return COUNTRIES.find(
    (c) =>
      c.zh === trimmed ||
      c.en === trimmed ||
      c.en.toLowerCase() === trimmed.toLowerCase() ||
      c.code === trimmed.toUpperCase()
  );
}

// 根据中文名获取国家代码
export function getCountryCode(name?: string): string | undefined {
  return findCountry(name)?.code;
}
